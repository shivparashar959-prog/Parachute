"""
Deterministic Mock AI Provider for DocGuard (Milestone 6).

Works offline without an API key, never pretends to have contacted Gemini,
and generates structured, evidence-traceable explanations and minimal
Markdown correction suggestions strictly from the supplied DriftFinding fields.
"""

import re
from typing import List, Optional, Tuple

from app.ai.base_provider import BaseAIProvider
from app.ai.prompt_builder import detect_prompt_injection_patterns
from app.ai.response_validator import validate_ai_response
from app.schemas.ai_explanation import (
    AIExplanationPayload,
    AIProviderType,
    CorrectionStatus,
)
from app.schemas.drift import DriftFinding


def _extract_First_def_line(code_snippet: str) -> str:
    """Return the first signature/header line from a code snippet."""
    if not code_snippet:
        return ""
    return code_snippet.strip().splitlines()[0].strip()


def _extract_quoted_tokens(reason: str) -> List[str]:
    """Extract single-quoted tokens from a deterministic finding reason string."""
    return re.findall(r"'([^']+)'", reason or "")


def _build_surgical_correction(
    finding: DriftFinding,
) -> Tuple[Optional[str], CorrectionStatus, bool, List[str]]:
    """
    Attempt to derive a minimal, evidence-traceable Markdown correction from the
    supplied finding without inventing any undocumented behavior.

    Returns:
        (suggested_correction, correction_status, insufficient_evidence, limitations)
    """
    limitations: List[str] = [
        "Generated by DocGuard Mock AI Mode (deterministic rule-based synthesis; no external LLM call)."
    ]

    # Check for prompt injection patterns in untrusted repository text and record a limitation note
    inj_hits = (
        detect_prompt_injection_patterns(finding.documentation_text)
        + detect_prompt_injection_patterns(finding.old_code_evidence)
        + detect_prompt_injection_patterns(finding.new_code_evidence)
    )
    if inj_hits:
        limitations.append(
            "Untrusted prompt-like instructions detected inside repository content were ignored as passive data."
        )

    if finding.status == "UNCERTAIN" or finding.confidence < 0.60:
        limitations.append(
            "Finding has UNCERTAIN status or weak/ambiguous mapping confidence; automated text replacement is withheld."
        )
        return None, "INSUFFICIENT_EVIDENCE", True, limitations

    if finding.status == "RESOLVED":
        return (
            finding.documentation_text,
            "SUGGESTION_AVAILABLE",
            False,
            limitations,
        )

    doc_text = finding.documentation_text
    old_sig = _extract_First_def_line(finding.old_code_evidence)
    new_sig = _extract_First_def_line(finding.new_code_evidence)

    # 1. RULE_A_CHANGED_DEFAULT: Replace old default literal with new default literal in doc_text
    if finding.rule_id == "RULE_A_CHANGED_DEFAULT":
        m = re.search(
            r"states default value (.+?) for parameter '([^']+)' .*? is now ([^.]+)\.",
            finding.reason,
        )
        if m:
            old_val_raw = m.group(1).strip()
            param_name = m.group(2).strip()
            new_val_raw = m.group(3).strip()
            old_unquoted = old_val_raw.strip("'\"")
            new_unquoted = new_val_raw.strip("'\"")

            updated = doc_text
            if old_val_raw in updated:
                updated = updated.replace(old_val_raw, new_val_raw)
            elif old_unquoted:
                updated = re.sub(
                    rf"(?<![A-Za-z0-9_]){re.escape(old_unquoted)}(?![A-Za-z0-9_])",
                    new_unquoted,
                    updated,
                )

            if updated != doc_text:
                return updated, "SUGGESTION_AVAILABLE", False, limitations

            return (
                f"{doc_text}\n\n*(Note: The default value for `{param_name}` in `{finding.qualified_symbol}` is now `{new_val_raw}`.)*",
                "REVIEW_REQUIRED",
                False,
                limitations,
            )

    # 2. RULE_B_REMOVED_OR_RENAMED_PARAMETER
    if finding.rule_id == "RULE_B_REMOVED_OR_RENAMED_PARAMETER":
        if finding.finding_type == "PARAMETER_RENAMED":
            m = re.search(
                r"old parameter name '([^']+)' .*? renamed to '([^']+)'",
                finding.reason,
            )
            if m:
                old_p, new_p = m.group(1), m.group(2)
                updated = re.sub(
                    rf"(?<![A-Za-z0-9_]){re.escape(old_p)}(?![A-Za-z0-9_])",
                    new_p,
                    doc_text,
                )
                if updated != doc_text:
                    return updated, "SUGGESTION_AVAILABLE", False, limitations

        if finding.finding_type == "PARAMETER_REMOVED":
            m = re.search(r"references parameter '([^']+)'", finding.reason)
            old_p = m.group(1) if m else "removed_parameter"
            clean_new_sig = new_sig.removeprefix("def ").removeprefix("async def ").rstrip(":")
            return (
                f"Call `{clean_new_sig}` (parameter `{old_p}` was removed from `{finding.qualified_symbol}`).",
                "REVIEW_REQUIRED",
                False,
                limitations,
            )

    # 3. RULE_C_ADDED_REQUIRED_PARAMETER
    if finding.rule_id == "RULE_C_ADDED_REQUIRED_PARAMETER":
        clean_new_sig = new_sig.removeprefix("def ").removeprefix("async def ").rstrip(":")
        m = re.search(r"required parameter '([^']+)'", finding.reason)
        req_p = m.group(1) if m else "new_parameter"
        return (
            f"{doc_text}\n\nEnsure required parameter `{req_p}` is provided when calling `{clean_new_sig}`.",
            "SUGGESTION_AVAILABLE",
            False,
            limitations,
        )

    # 4. RULE_D_RETURN_CONTRACT_CHANGED
    if finding.rule_id == "RULE_D_RETURN_CONTRACT_CHANGED":
        m = re.search(r"changed from '([^']+)' to '([^']+)'", finding.reason)
        if m:
            old_ret, new_ret = m.group(1), m.group(2)
            limitations.append(
                "Type annotation changes do not guarantee runtime return value changes; human verification is required."
            )
            updated = doc_text.replace(old_ret, new_ret)
            if updated != doc_text:
                return updated, "REVIEW_REQUIRED", False, limitations
            return (
                f"{doc_text} (Updated return annotation: `{new_ret}`.)",
                "REVIEW_REQUIRED",
                False,
                limitations,
            )

    # 5. RULE_F_SYMBOL_RENAMED
    if finding.rule_id == "RULE_F_SYMBOL_RENAMED":
        m = re.search(
            r"old function name '([^']+)'[,]? which was renamed to '([^']+)'",
            finding.reason,
        )
        if m:
            old_fn, new_fn = m.group(1), m.group(2)
            old_short = old_fn.split(".")[-1]
            new_short = new_fn.split(".")[-1]
            updated = doc_text.replace(old_fn, new_fn).replace(old_short, new_short)
            if updated != doc_text:
                return updated, "SUGGESTION_AVAILABLE", False, limitations

    # 6. RULE_E_SYMBOL_REMOVED / RULE_G_DELETED_SOURCE_FILE
    if finding.rule_id in {"RULE_E_SYMBOL_REMOVED", "RULE_G_DELETED_SOURCE_FILE"}:
        limitations.append(
            f"Symbol or file '{finding.qualified_symbol}' was deleted without a direct replacement in the AST diff."
        )
        return (
            f"<!-- Remove or replace documentation for removed symbol/file `{finding.qualified_symbol}` ({finding.source_file}) -->",
            "REVIEW_REQUIRED",
            False,
            limitations,
        )

    # 7. RULE_H_SIGNATURE_CHANGED
    if finding.rule_id == "RULE_H_SIGNATURE_CHANGED" and new_sig:
        clean_new_sig = new_sig.removeprefix("def ").removeprefix("async def ").rstrip(":")
        return (
            f"Update usage in `{finding.documentation_file}` to match the current signature `{clean_new_sig}`.",
            "REVIEW_REQUIRED",
            False,
            limitations,
        )

    limitations.append(
        "Insufficient deterministic evidence to synthesize an exact replacement statement automatically."
    )
    return None, "INSUFFICIENT_EVIDENCE", True, limitations


class MockAIProvider(BaseAIProvider):
    """
    Deterministic Mock AI provider for offline development, testing, and demonstrations.
    """

    @property
    def provider_name(self) -> AIProviderType:
        return "mock"

    @property
    def model_name(self) -> str:
        return "docguard-deterministic-mock-v1"

    def generate_explanation(self, finding: DriftFinding) -> AIExplanationPayload:
        old_sig = _extract_First_def_line(finding.old_code_evidence)
        new_sig = _extract_First_def_line(finding.new_code_evidence)

        code_change_summary = (
            f"In '{finding.source_file}' (line {finding.source_line or finding.old_source_line or 1}), "
            f"`{finding.qualified_symbol}` underwent a `{finding.finding_type}` change "
            f"from `{old_sig}` to `{new_sig}`."
        )

        documentation_issue = (
            f"In '{finding.documentation_file}' (line {finding.documentation_line}), "
            f"the documentation statement (\"{finding.documentation_text[:180]}\") "
            f"conflicts with or does not reflect the current `{finding.qualified_symbol}` definition. "
            f"{finding.reason}"
        )

        evidence_used: List[str] = [
            f"Base code evidence ({finding.source_file}:L{finding.old_source_line or 1}): {old_sig}",
            f"Head code evidence ({finding.source_file}:L{finding.source_line or 1}): {new_sig}",
            f"Documentation statement ({finding.documentation_file}:L{finding.documentation_line}): {finding.documentation_text[:140]}",
            f"Detection rule: {finding.rule_id} (deterministic status: {finding.status}, confidence: {finding.confidence})",
        ]
        for map_ev in finding.mapping_evidence[:3]:
            evidence_used.append(f"Mapping evidence: {map_ev}")

        (
            suggested_correction,
            correction_status,
            insufficient_evidence,
            limitations,
        ) = _build_surgical_correction(finding)

        explanation = (
            f"[Mock AI Explanation] 1. Code Change: {code_change_summary} "
            f"2. Current Documentation: At '{finding.documentation_file}' line {finding.documentation_line}, "
            f"the documentation states: \"{finding.documentation_text[:160]}\". "
            f"3. Why Outdated: {finding.reason} "
            f"4. Supporting Evidence: Linked via {', '.join(finding.mapping_evidence[:2]) or 'exact symbol match'}. "
            f"5. Author Review Action: {finding.suggested_action}"
        )

        raw_payload = {
            "explanation": explanation,
            "code_change_summary": code_change_summary,
            "documentation_issue": documentation_issue,
            "evidence_used": evidence_used,
            "suggested_correction": suggested_correction,
            "correction_status": correction_status,
            "correction_available": bool(
                suggested_correction and not insufficient_evidence
            ),
            "insufficient_evidence": insufficient_evidence,
            "limitations": limitations,
        }

        return validate_ai_response(raw_payload, finding)
